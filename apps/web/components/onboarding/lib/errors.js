export function isKnownError(code) {
  return KNOWN.has(code);
}

/** Message for a { error: CODE } result, a thrown error, or a bare code string. */
export function errorMessage(t, errOrCode) {
  const code = typeof errOrCode === "string" ? errOrCode : errOrCode?.error;
  return KNOWN.has(code) ? t(`errors.${code}`) : t("errors.generic");
}
